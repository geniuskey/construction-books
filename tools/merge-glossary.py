#!/usr/bin/env python3
"""Merge per-chapter glossary files <book>/js/glossary/<slug>.json into <book>/js/glossary-data.js (series schema v1).
Same `ko` → one entry (first definition wins, chapters merged). Order follows the book's chapter list. Usage: merge-glossary.py <book>"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
book = ROOT / (sys.argv[1] if len(sys.argv) > 1 else 'materials')
order = re.findall(r'slug:\s*"([^"]+)"', (book / 'js/common.js').read_text().split('const CB =')[0])
files = sorted((book / 'js/glossary').glob('*.json'), key=lambda p: order.index(p.stem) if p.stem in order else 99)
terms, seen = [], {}
for f in files:
    for t in json.loads(f.read_text()):
        t.setdefault('abbr', ''); t.setdefault('chapters', [f.stem])
        key = t['ko'].strip()
        if key in seen:
            seen[key]['chapters'] = list(dict.fromkeys(seen[key]['chapters'] + t['chapters']))
            continue
        entry = {k: t[k] for k in ('ko', 'en', 'abbr', 'def', 'chapters')}
        entry.update({k: v for k, v in t.items() if k not in entry})
        seen[key] = entry; terms.append(entry)
head = '''/* Copyright (c) 2026 geniuskey and Book Series contributors.
   Code: MIT. Definitions: CC-BY-4.0 (see the book license). */
/* Series glossary schema v1: ko, en, abbr, def, chapters[]; optional category, related, audio, examples, stage.
   This is the source of truth for both the glossary page and prose tooltips.
   Generated by tools/merge-glossary.py from js/glossary/*.json. */
'''
body = ',\n'.join('    ' + json.dumps(t, ensure_ascii=False) for t in terms)
(book / 'js/glossary-data.js').write_text(head + 'window.BOOK_GLOSSARY = {\n  version: 1,\n  terms: [\n' + body + '\n  ]\n};\n')
print(f'{book.name}: {len(terms)} terms from {len(files)} files')
